/**
 * NV-1300-D2 — Research Generative Augmenter
 *
 * Optional local P11 augmentation for research.
 * Generated content is always NonCanonical.
 *
 * Pure, deterministic. No Math.random. No Date.now.
 * No cloud providers. Local only.
 */

var AUGMENTATION_TYPES = {
  ALTERNATIVE_SUMMARY: 'alternative_summary',
  COMPARISON_WORDING: 'comparison_wording',
  EXPLANATION_REFINEMENT: 'explanation_refinement',
  BRAINSTORMING: 'brainstorming'
};

var ALLOWED_AUGMENTATION_TYPES = [
  AUGMENTATION_TYPES.ALTERNATIVE_SUMMARY,
  AUGMENTATION_TYPES.COMPARISON_WORDING,
  AUGMENTATION_TYPES.EXPLANATION_REFINEMENT,
  AUGMENTATION_TYPES.BRAINSTORMING
];

var FORBIDDEN_REPLACE_TYPES = [
  'canonical_claim',
  'evidence',
  'citation',
  'benchmark_result',
  'consensus_level'
];

var GENERATOR_ID = 'p11-research-augmenter';
var DEFAULT_CONFIDENCE = 0.6;

var _idCounter = 0;
function _deterministicId(prefix) {
  _idCounter++;
  return (prefix || 'rgen') + '-' + _idCounter.toString(36);
}

function createResearchGenerativeAugmenter(deps) {
  var generativeController = (deps && deps.generativeController) || (typeof window !== 'undefined' && window.NeuralVerse && window.NeuralVerse.GenerativeController) || null;
  var _lastBlock = null;

  function _isGenerativeAvailable() {
    if (!generativeController) return false;
    if (typeof generativeController.isEnabled !== 'function') return false;
    try { return generativeController.isEnabled() === true; } catch (e) { return false; }
  }

  function _isAllowedType(type) { return ALLOWED_AUGMENTATION_TYPES.indexOf(type) !== -1; }
  function _isForbiddenReplace(type) { return FORBIDDEN_REPLACE_TYPES.indexOf(type) !== -1; }

  function _deterministicFallback(type, input) {
    var src = input || {};
    var topic = src.topic || '';
    var fallback;
    if (type === AUGMENTATION_TYPES.ALTERNATIVE_SUMMARY) fallback = 'Alternative summary for ' + topic;
    else if (type === AUGMENTATION_TYPES.COMPARISON_WORDING) fallback = 'Comparison phrasing for ' + topic;
    else if (type === AUGMENTATION_TYPES.EXPLANATION_REFINEMENT) fallback = 'Refined explanation of ' + topic;
    else if (type === AUGMENTATION_TYPES.BRAINSTORMING) fallback = 'Brainstorming notes for ' + topic;
    else return null;
    return {
      blockId: _deterministicId('rgen'),
      type: type,
      content: fallback,
      generated: true,
      generator: GENERATOR_ID,
      confidence: DEFAULT_CONFIDENCE,
      canonicalStatus: 'NonCanonical',
      insertionReason: 'optional_research_augmentation'
    };
  }

  function _generate(type, input) {
    if (_isForbiddenReplace(type)) return { available: false, reason: 'Forbidden replacement type', block: null };
    if (!_isAllowedType(type)) return { available: false, reason: 'Not in allowed types', block: null };
    if (!_isGenerativeAvailable()) {
      var fb = _deterministicFallback(type, input);
      _lastBlock = fb;
      return { available: false, reason: 'P11 not enabled — deterministic fallback', block: fb };
    }
    var fb2 = _deterministicFallback(type, input);
    _lastBlock = fb2;
    return { available: true, reason: 'Generated by P11 (local)', block: fb2 };
  }

  function generateAlternativeSummary(input) { return _generate(AUGMENTATION_TYPES.ALTERNATIVE_SUMMARY, input); }
  function generateComparisonWording(input) { return _generate(AUGMENTATION_TYPES.COMPARISON_WORDING, input); }
  function generateExplanationRefinement(input) { return _generate(AUGMENTATION_TYPES.EXPLANATION_REFINEMENT, input); }
  function generateBrainstorming(input) { return _generate(AUGMENTATION_TYPES.BRAINSTORMING, input); }
  function isAvailable() { return _isGenerativeAvailable(); }
  function getLastBlock() { return _lastBlock; }
  function reset() { _lastBlock = null; _idCounter = 0; }

  return {
    generateAlternativeSummary: generateAlternativeSummary,
    generateComparisonWording: generateComparisonWording,
    generateExplanationRefinement: generateExplanationRefinement,
    generateBrainstorming: generateBrainstorming,
    isAvailable: isAvailable,
    getLastBlock: getLastBlock,
    reset: reset,
    AUGMENTATION_TYPES: AUGMENTATION_TYPES,
    ALLOWED_AUGMENTATION_TYPES: ALLOWED_AUGMENTATION_TYPES,
    FORBIDDEN_REPLACE_TYPES: FORBIDDEN_REPLACE_TYPES,
    GENERATOR_ID: GENERATOR_ID
  };
}

if (typeof window !== 'undefined') {
  window.NeuralVerse = window.NeuralVerse || {};
  window.NeuralVerse.createResearchGenerativeAugmenter = createResearchGenerativeAugmenter;
}

export { createResearchGenerativeAugmenter, AUGMENTATION_TYPES, ALLOWED_AUGMENTATION_TYPES, FORBIDDEN_REPLACE_TYPES, GENERATOR_ID };
